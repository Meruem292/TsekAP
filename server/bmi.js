export function completedAgeMonths(dob, onDate = new Date()) {
  const birth = new Date(`${dob}T00:00:00Z`);
  if (Number.isNaN(birth.getTime())) return NaN;
  let months = (onDate.getUTCFullYear() - birth.getUTCFullYear()) * 12 + onDate.getUTCMonth() - birth.getUTCMonth();
  if (onDate.getUTCDate() < birth.getUTCDate()) months -= 1;
  return months;
}

export function calculateBmi(height, weight, ageMonths, sex) {
  const h = Number(height);
  const w = Number(weight);
  if (!Number.isFinite(h) || h < 100 || h > 220 || !Number.isFinite(w) || w < 25 || w > 200) {
    throw new Error("Enter a height from 100–220 cm and a weight from 25–200 kg.");
  }
  const row = WHO_LMS[sex]?.find(([month]) => month === ageMonths);
  if (!row) throw new Error("TsekAP currently supports students aged 15 through 18.");
  const bmi = w / ((h / 100) ** 2);
  const [, L, M, S] = row;
  const z = ((bmi / M) ** L - 1) / (L * S);
  const classification = z < -3 ? "Severe thinness" : z < -2 ? "Thinness" : z <= 1 ? "Within expected range" : z <= 2 ? "Overweight" : "Obesity";
  return { bmi, z, classification };
}
